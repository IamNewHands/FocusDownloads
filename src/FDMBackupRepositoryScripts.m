static NSError *FDMRepoError(NSString *message) {
    return [NSError errorWithDomain:@"FocusDM.Backup.Repository" code:1 userInfo:@{NSLocalizedDescriptionKey: message}];
}

// t_userscript columns this category owns. Confirmed from the host CREATE TABLE and INSERT statements.
static NSArray<NSString *> *FDMBackupScriptColumns(void) {
    static NSArray *columns;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        columns = @[@"uuid", @"name", @"author", @"version", @"namespace", @"desc", @"iconUrl", @"runAt",
                    @"selectFrame", @"frameOption", @"isAutoUpdate", @"updateUrl", @"downloadUrl",
                    @"content", @"isActive", @"ppOrder", @"sql_includes", @"sql_matches", @"sql_excludes",
                    @"sql_grants", @"sql_requireUrls", @"sql_resourceUrls", @"whiteList", @"blackList",
                    @"updateTime", @"ctime"];
    });
    return columns;
}

// Metadata carried through backup. `content` is the script body; everything else is matching and
// grant metadata the host uses to decide when and where to inject.
static NSArray<NSString *> *FDMBackupScriptMetadataKeys(void) {
    static NSArray *keys;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        keys = @[@"name", @"author", @"version", @"namespace", @"desc", @"iconUrl", @"runAt",
                 @"selectFrame", @"frameOption", @"isAutoUpdate", @"updateUrl", @"downloadUrl",
                 @"sql_includes", @"sql_matches", @"sql_excludes", @"sql_grants",
                 @"sql_requireUrls", @"sql_resourceUrls", @"whiteList", @"blackList"];
    });
    return keys;
}

// SQLite column for a portable metadata key.
static NSString *FDMBackupScriptColumnForKey(NSString *key) {
    if ([key isEqual:@"iconURL"]) return @"iconUrl";
    return key;
}

@interface FDMBackupScriptStagedSet : NSObject <FDMBackupStagedSet>
@property (nonatomic, copy) NSData *beforeSnapshot;
@property (nonatomic, copy) NSData *afterSnapshot;
@property (nonatomic, copy) NSArray<NSDictionary *> *rowsToWrite;
@property (nonatomic, copy) NSArray<NSString *> *idsToDelete;
// Script IDs whose .js file must be regenerated by the host after commit.
@property (nonatomic, copy) NSArray<NSString *> *idsToRegenerate;
@end

@implementation FDMBackupScriptStagedSet
@end

@implementation FDMBackupScriptsRepository {
    id<FDMBackupSQLDatabase> _database;
    NSArray *_publishedModels;
}

- (instancetype)initWithDatabase:(id<FDMBackupSQLDatabase>)database {
    if ((self = [super init])) _database = database;
    return self;
}

- (NSString *)categoryIdentifier { return FDMBackupCategoryScripts; }

- (BOOL)isAvailable { return _database != nil; }

- (NSString *)storageDomain { return @"host.sqlite3"; }

- (BOOL)applyStaged:(id)staged onExecutor:(id<FDMBackupSQLExecutor>)executor error:(NSError **)error {
    FDMBackupScriptStagedSet *set = staged;
    if (![set isKindOfClass:FDMBackupScriptStagedSet.class]) { if (error) *error = FDMRepoError(@"暂存集无效"); return NO; }
    return [self writeStagedSet:set onExecutor:executor error:error];
}

- (BOOL)writeStagedSet:(FDMBackupScriptStagedSet *)set
            onExecutor:(id<FDMBackupSQLExecutor>)executor
                 error:(NSError **)error {
    NSSet *columns = nil;
    if (!FDMBackupTableColumns(executor, @"t_userscript", &columns, error)) return NO;
    if (set.idsToDelete.count) {
        NSMutableArray *marks = [NSMutableArray array];
        for (NSUInteger i = 0; i < set.idsToDelete.count; i++) [marks addObject:@"?"];
        NSString *sql = [NSString stringWithFormat:@"DELETE FROM t_userscript WHERE uuid IN (%@)",
                         [marks componentsJoinedByString:@","]];
        if (![executor update:sql parameters:set.idsToDelete error:error]) return NO;
    }
    for (NSDictionary *script in set.rowsToWrite) {
        NSMutableArray *names = [NSMutableArray array];
        NSMutableArray *marks = [NSMutableArray array];
        NSMutableArray *values = [NSMutableArray array];
        void (^add)(NSString *, id) = ^(NSString *column, id value) {
            if (![columns containsObject:column]) return;
            [names addObject:column];
            [marks addObject:@"?"];
            [values addObject:value ?: NSNull.null];
        };
        add(@"uuid", script[@"id"]);
        for (NSString *key in FDMBackupScriptMetadataKeys()) {
            add(FDMBackupScriptColumnForKey(key), script[key]);
        }
        add(@"content", script[@"content"]);
        add(@"isActive", script[@"enabled"] ?: @0);
        add(@"ppOrder", @0);
        if (script[@"ppOrder"]) add(@"ppOrder", script[@"ppOrder"]);
        NSString *now = [NSString stringWithFormat:@"%.0f", NSDate.date.timeIntervalSince1970];
        add(@"updateTime", now);
        add(@"ctime", now);
        NSString *sql = [NSString stringWithFormat:@"INSERT OR REPLACE INTO t_userscript (%@) VALUES (%@)",
                         [names componentsJoinedByString:@","], [marks componentsJoinedByString:@","]];
        if (![executor update:sql parameters:values error:error]) return NO;
    }
    return YES;
}

- (NSData *)commitStaged:(id)staged error:(NSError **)error {
    FDMBackupScriptStagedSet *set = staged;
    if (![set isKindOfClass:FDMBackupScriptStagedSet.class]) { if (error) *error = FDMRepoError(@"暂存集无效"); return nil; }
    __block NSError *failure = nil;
    BOOL ok = [_database inTransaction:^BOOL(id<FDMBackupSQLExecutor> executor) {
        return [self writeStagedSet:set onExecutor:executor error:&failure];
    } error:&failure];
    if (!ok) { if (error) *error = failure ?: FDMRepoError(@"脚本写入失败"); return nil; }
    return set.afterSnapshot;
}

- (NSArray<NSDictionary *> *)readRowsWithError:(NSError **)error {
    __block NSArray *rows = nil;
    __block NSError *failure = nil;
    [_database inDatabase:^(id<FDMBackupSQLExecutor> executor) {
        NSSet *columns = nil;
        if (!FDMBackupTableColumns(executor, @"t_userscript", &columns, &failure)) return;
        NSMutableArray *selected = [NSMutableArray array];
        for (NSString *column in FDMBackupScriptColumns()) if ([columns containsObject:column]) [selected addObject:column];
        NSString *sql = [NSString stringWithFormat:@"SELECT %@ FROM t_userscript ORDER BY uuid",
                         [selected componentsJoinedByString:@","]];
        rows = [executor query:sql parameters:nil error:&failure];
    }];
    if (failure) { if (error) *error = failure; return nil; }
    return rows ?: @[];
}

- (NSData *)exportSnapshotWithRevision:(NSString **)revision error:(NSError **)error {
    NSArray *rows = [self readRowsWithError:error];
    if (!rows) return nil;
    NSMutableArray *scripts = [NSMutableArray array];
    for (NSDictionary *row in rows) {
        NSString *identifier = FDMJSONStringValue(row[@"uuid"]);
        NSString *content = FDMJSONStringValue(row[@"content"]);
        if (!identifier.length || !content.length) { if (error) *error = FDMRepoError(@"脚本记录损坏，未导出不完整备份"); return nil; }
        if ([content lengthOfBytesUsingEncoding:NSUTF8StringEncoding] > FDMBackupMaxScriptBytes || rows.count > FDMBackupMaxScripts) {
            if (error) *error = FDMRepoError(@"脚本数量或原文超过备份预算，未截断导出"); return nil;
        }
        NSMutableDictionary *script = [@{@"id": identifier, @"content": content} mutableCopy];
        for (NSString *key in FDMBackupScriptMetadataKeys()) {
            id value = row[FDMBackupScriptColumnForKey(key)];
            if (!value || value == NSNull.null) continue;
            if ([value isKindOfClass:NSString.class]) {
                if ([value length]) script[key] = value;
            } else if ([value isKindOfClass:NSNumber.class]) {
                script[key] = value;
            }
        }
        script[@"enabled"] = @([row[@"isActive"] boolValue]);
        [scripts addObject:script];
        if (scripts.count >= FDMBackupMaxScripts) break;
    }
    NSData *payload = FDMJSONCanonicalData(@{@"schemaVersion": @1, @"scripts": scripts}, error);
    if (payload && revision) *revision = FDMBackupSHA256(payload);
    return payload;
}

- (NSString *)currentRevisionWithError:(NSError **)error {
    NSString *revision = nil;
    if (![self exportSnapshotWithRevision:&revision error:error]) return nil;
    return revision;
}

- (id)validateImportPayload:(NSData *)payload error:(NSError **)error {
    id root = FDMJSONParseData(payload, error);
    NSDictionary *document = FDMJSONObjectValue(root);
    if (!document) { if (error) *error = FDMRepoError(@"脚本数据必须是对象"); return nil; }
    for (NSString *key in document) {
        if (![@[@"schemaVersion", @"scripts"] containsObject:key]) { if (error) *error = FDMRepoError(@"脚本数据含未知字段"); return nil; }
    }
    unsigned long long schema = 0;
    if (!FDMJSONNonNegativeInteger(document[@"schemaVersion"], 100, &schema) || schema != 1) {
        if (error) *error = FDMRepoError(@"脚本数据版本不受支持");
        return nil;
    }
    NSArray *scripts = FDMJSONArrayValue(document[@"scripts"]);
    if (!scripts || scripts.count > FDMBackupMaxScripts) { if (error) *error = FDMRepoError(@"脚本数量超出上限"); return nil; }
    NSMutableArray *validated = [NSMutableArray array];
    NSMutableSet *ids = [NSMutableSet set];
    NSSet *allowed = [NSSet setWithArray:[@[@"id", @"content", @"enabled"] arrayByAddingObjectsFromArray:FDMBackupScriptMetadataKeys()]];
    for (id raw in scripts) {
        NSDictionary *row = FDMJSONObjectValue(raw);
        if (!row) { if (error) *error = FDMRepoError(@"脚本条目无效"); return nil; }
        for (NSString *key in row) {
            if (![allowed containsObject:key]) { if (error) *error = FDMRepoError([NSString stringWithFormat:@"脚本条目含未知字段：%@", key]); return nil; }
        }
        NSString *identifier = FDMJSONStringValue(row[@"id"]);
        NSString *name = FDMJSONStringValue(row[@"name"]);
        NSString *content = FDMJSONStringValue(row[@"content"]);
        if (!identifier.length || identifier.length > 128 || [identifier rangeOfCharacterFromSet:[[NSCharacterSet characterSetWithCharactersInString:@"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_"] invertedSet]].location != NSNotFound) { if (error) *error = FDMRepoError(@"脚本缺少有效标识"); return nil; }
        if ([ids containsObject:identifier]) { if (error) *error = FDMRepoError(@"脚本标识重复"); return nil; }
        [ids addObject:identifier];
        if (!name.length || [name lengthOfBytesUsingEncoding:NSUTF8StringEncoding] > FDMBackupMaxNameBytes) {
            if (error) *error = FDMRepoError(@"脚本名称无效");
            return nil;
        }
        if (!content.length) { if (error) *error = FDMRepoError(@"脚本内容为空"); return nil; }
        if ([content lengthOfBytesUsingEncoding:NSUTF8StringEncoding] > FDMBackupMaxScriptBytes) {
            if (error) *error = FDMRepoError(@"脚本内容超出单条上限");
            return nil;
        }
        if (row[@"enabled"] && CFGetTypeID((__bridge CFTypeRef)row[@"enabled"]) != CFBooleanGetTypeID()) {
            if (error) *error = FDMRepoError(@"enabled 必须是布尔值");
            return nil;
        }
        NSMutableDictionary *script = [@{@"id": identifier, @"name": name, @"content": content} mutableCopy];
        for (NSString *key in FDMBackupScriptMetadataKeys()) {
            id value = row[key];
            if (!value || value == NSNull.null) continue;
            if ([value isKindOfClass:NSString.class]) {
                if ([value lengthOfBytesUsingEncoding:NSUTF8StringEncoding] > FDMBackupMaxURLBytes) {
                    if (error) *error = FDMRepoError([NSString stringWithFormat:@"脚本字段过长：%@", key]);
                    return nil;
                }
                script[key] = value;
            } else if ([value isKindOfClass:NSNumber.class]) {
                unsigned long long number = 0;
                if (!FDMJSONNonNegativeInteger(value, 1000000, &number)) {
                    if (error) *error = FDMRepoError([NSString stringWithFormat:@"脚本数值字段无效：%@", key]);
                    return nil;
                }
                script[key] = @(number);
            } else {
                if (error) *error = FDMRepoError([NSString stringWithFormat:@"脚本字段类型无效：%@", key]);
                return nil;
            }
        }
        [validated addObject:script];
    }
    return [validated copy];
}

- (NSDictionary<NSString *, NSNumber *> *)previewCountsForValidated:(id)validated error:(NSError **)error {
    NSArray *live = [self readRowsWithError:error];
    if (!live) return nil;
    NSMutableDictionary *byID = [NSMutableDictionary dictionary];
    for (NSDictionary *row in live) {
        NSString *identifier = FDMJSONStringValue(row[@"uuid"]);
        if (identifier.length) byID[identifier] = row;
    }
    NSUInteger added = 0, identical = 0, conflict = 0;
    for (NSDictionary *script in validated) {
        NSDictionary *existing = byID[script[@"id"]];
        if (!existing) { added++; continue; }
        BOOL same = [FDMJSONStringValue(existing[@"content"]) isEqual:script[@"content"]] &&
                    [FDMJSONStringValue(existing[@"name"]) isEqual:script[@"name"]];
        if (same) identical++; else conflict++;
    }
    // Every imported script arrives disabled, so the disabled count is the import size. An unchanged,
    // already-enabled local script keeps its state, and is reported separately as identical.
    NSUInteger disabled = 0;
    for (NSDictionary *script in validated) {
        NSDictionary *existing = byID[script[@"id"]];
        BOOL unchangedEnabled = existing && [existing[@"isActive"] boolValue] &&
            [FDMJSONStringValue(existing[@"content"]) isEqual:script[@"content"]] &&
            [FDMJSONStringValue(existing[@"name"]) isEqual:script[@"name"]];
        if (!unchangedEnabled) disabled++;
    }
    return @{FDMBackupCountAdded: @(added), FDMBackupCountIdentical: @(identical),
             FDMBackupCountConflict: @(conflict), FDMBackupCountDowngraded: @0,
             FDMBackupCountDisabled: @(disabled), FDMBackupCountUnsupported: @0};
}

- (id)stageMergeValidated:(id)validated replace:(BOOL)replace error:(NSError **)error {
    NSArray *live = [self readRowsWithError:error];
    if (!live) return nil;
    NSData *before = [self exportSnapshotWithRevision:NULL error:error];
    if (!before) return nil;
    NSMutableDictionary *liveByID = [NSMutableDictionary dictionary];
    for (NSDictionary *row in live) {
        NSString *identifier = FDMJSONStringValue(row[@"uuid"]);
        if (identifier.length) liveByID[identifier] = row;
    }
    NSMutableArray *toWrite = [NSMutableArray array];
    NSMutableArray *toRegenerate = [NSMutableArray array];
    for (NSDictionary *script in validated) {
        NSDictionary *existing = liveByID[script[@"id"]];
        BOOL unchanged = existing &&
            [FDMJSONStringValue(existing[@"content"]) isEqual:script[@"content"]] &&
            [FDMJSONStringValue(existing[@"name"]) isEqual:script[@"name"]];
        if (unchanged) {
            // Same script, unchanged: keep the local row exactly, including its enabled state.
            continue;
        }
        if (existing && !replace) {
            // keep-local: an existing row with different content is a conflict we do not overwrite.
            continue;
        }
        NSMutableDictionary *row = [script mutableCopy];
        // A new or changed script is imported disabled; the user must enable it explicitly.
        row[@"enabled"] = @NO;
        [toWrite addObject:row];
        [toRegenerate addObject:script[@"id"]];
    }
    NSMutableArray *toDelete = [NSMutableArray array];
    if (replace) {
        NSMutableSet *imported = [NSMutableSet set];
        for (NSDictionary *script in validated) [imported addObject:script[@"id"]];
        for (NSString *identifier in liveByID) if (![imported containsObject:identifier]) [toDelete addObject:identifier];
    }
    FDMBackupScriptStagedSet *staged = [[FDMBackupScriptStagedSet alloc] init];
    staged.beforeSnapshot = before;
    staged.rowsToWrite = toWrite;
    staged.idsToDelete = toDelete;
    staged.idsToRegenerate = toRegenerate;

    NSMutableDictionary *afterByID = [NSMutableDictionary dictionary];
    id beforeRoot = FDMJSONParseData(before, NULL);
    for (NSDictionary *script in FDMJSONArrayValue(FDMJSONObjectValue(beforeRoot)[@"scripts"])) afterByID[script[@"id"]] = script;
    for (NSString *identifier in toDelete) [afterByID removeObjectForKey:identifier];
    for (NSDictionary *script in toWrite) afterByID[script[@"id"]] = script;
    // Sorted by uuid so the read-back bytes match a fresh export (which uses ORDER BY uuid).
    NSArray *sortedScripts = [afterByID.allValues sortedArrayUsingComparator:^NSComparisonResult(NSDictionary *a, NSDictionary *b) {
        return [a[@"id"] compare:b[@"id"]];
    }];
    NSData *after = FDMJSONCanonicalData(@{@"schemaVersion": @1, @"scripts": sortedScripts}, error);
    if (!after) return nil;
    staged.afterSnapshot = after;
    return staged;
}

- (id)stageRestoreSnapshot:(NSData *)snapshot error:(NSError **)error {
    id validated = [self validateImportPayload:snapshot error:error];
    if (!validated) return nil;
    NSArray *live = [self readRowsWithError:error];
    if (!live) return nil;
    NSMutableSet *kept = [NSMutableSet set];
    for (NSDictionary *script in validated) [kept addObject:script[@"id"]];
    NSMutableArray *toDelete = [NSMutableArray array];
    for (NSDictionary *row in live) {
        NSString *identifier = FDMJSONStringValue(row[@"uuid"]);
        if (identifier.length && ![kept containsObject:identifier]) [toDelete addObject:identifier];
    }
    FDMBackupScriptStagedSet *set = [[FDMBackupScriptStagedSet alloc] init];
    set.beforeSnapshot = [self exportSnapshotWithRevision:NULL error:NULL] ?: [NSData data];
    set.afterSnapshot = snapshot;
    set.rowsToWrite = validated;
    set.idsToDelete = toDelete;
    set.idsToRegenerate = [validated valueForKey:@"id"];
    return set;
}

- (BOOL)rollbackStaged:(id)staged error:(NSError **)error {
    FDMBackupScriptStagedSet *set = staged;
    if (![set isKindOfClass:FDMBackupScriptStagedSet.class]) { if (error) *error = FDMRepoError(@"暂存集无效"); return NO; }
    id restore = [self stageRestoreSnapshot:set.beforeSnapshot error:error];
    if (!restore) return NO;
    return [self commitStaged:restore error:error] != nil;
}

// The host's .js file stores the original source (loadJsWithUUID: reads it and calls its parser).
// Executor generation is delegated to the same UserScript model that the host's SQL query uses.
- (NSString *)scriptDirectoryWithError:(NSError **)error {
    Class cls = NSClassFromString(@"Tampermonkey"); SEL shared = NSSelectorFromString(@"shareInstance");
    id manager = [cls respondsToSelector:shared] ? ((id (*)(id, SEL))objc_msgSend)(cls, shared) : nil;
    NSString *directory = FDMString(FDMValue(manager, @"scriptPath"));
    if (!directory.length) { if (error) *error = FDMRepoError(@"原生脚本目录不可用"); return nil; }
    NSString *standard = directory.stringByStandardizingPath;
    NSString *documents = FDMDocumentsPath().stringByStandardizingPath;
    NSString *library = NSSearchPathForDirectoriesInDomains(NSLibraryDirectory, NSUserDomainMask, YES).firstObject.stringByStandardizingPath;
    if (![standard hasPrefix:[documents stringByAppendingString:@"/"]] && ![standard hasPrefix:[library stringByAppendingString:@"/"]]) {
        if (error) *error = FDMRepoError(@"脚本目录不属于本应用配置范围"); return nil;
    }
    NSError *failure = nil;
    if (![[NSFileManager defaultManager] createDirectoryAtPath:standard withIntermediateDirectories:YES attributes:nil error:&failure]) { if (error) *error = failure; return nil; }
    if (![standard.stringByResolvingSymlinksInPath isEqual:standard]) { if (error) *error = FDMRepoError(@"脚本目录是符号链接，未写入"); return nil; }
    return standard;
}
- (NSString *)fileNameForID:(NSString *)identifier {
    if (!identifier.length || identifier.length > 128 || [identifier rangeOfCharacterFromSet:[[NSCharacterSet characterSetWithCharactersInString:@"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_"] invertedSet]].location != NSNotFound) return nil;
    return [[identifier stringByReplacingOccurrencesOfString:@"-" withString:@"_"] stringByAppendingString:@".js"];
}
- (BOOL)regenerateHostScriptFilesWithError:(NSError **)error {
    NSArray *rows = [self readRowsWithError:error]; if (!rows) return NO;
    if (!rows.count) { _publishedModels = @[]; return YES; }
    NSString *directory = [self scriptDirectoryWithError:error]; if (!directory) return NO;
    Class cls = NSClassFromString(@"UserScript");
    SEL initialize = NSSelectorFromString(@"initWithDictionary:error:"), fromSQL = NSSelectorFromString(@"jsonModelFromSql"), generate = NSSelectorFromString(@"updateExecutorJs");
    if (!cls || ![cls instancesRespondToSelector:initialize] || ![cls instancesRespondToSelector:generate] || ![cls instancesRespondToSelector:fromSQL]) {
        if (error) *error = FDMRepoError(@"宿主缺少已验证的用户脚本模型接口"); return NO;
    }
    NSMutableArray *models = [NSMutableArray array];
    for (NSDictionary *row in rows) {
        NSString *name = [self fileNameForID:FDMJSONStringValue(row[@"uuid"])];
        NSString *content = FDMJSONStringValue(row[@"content"]);
        if (!name || !content.length) { if (error) *error = FDMRepoError(@"脚本内容或标识无效"); return NO; }
        NSError *modelError = nil;
        id model = ((id (*)(id, SEL, id, NSError **))objc_msgSend)([cls alloc], initialize, row, &modelError);
        if (!model) { if (error) *error = FDMRepoError(@"原生脚本模型无法还原"); return NO; }
        @try {
            ((void (*)(id, SEL))objc_msgSend)(model, fromSQL);
            ((void (*)(id, SEL))objc_msgSend)(model, generate);
        } @catch (NSException *exception) { if (error) *error = FDMRepoError(@"脚本执行代码再生失败，恢复将回滚"); return NO; }
        NSString *executor = FDMString(FDMValue(model, @"executorJs"));
        if (!executor.length) { if (error) *error = FDMRepoError(@"宿主未生成脚本执行代码"); return NO; }
        NSData *bytes = [content dataUsingEncoding:NSUTF8StringEncoding]; NSString *path = [directory stringByAppendingPathComponent:name];
        NSNumber *symbolic = nil; [[NSURL fileURLWithPath:path] getResourceValue:&symbolic forKey:NSURLIsSymbolicLinkKey error:NULL];
        if (symbolic.boolValue || ![bytes writeToFile:path options:NSDataWritingAtomic error:error]) return NO;
        if (![FDMReadBoundedFile([NSURL fileURLWithPath:path], FDMBackupMaxScriptBytes, error) isEqual:bytes]) {
            if (error) *error = FDMRepoError(@"脚本源文件读回不一致"); return NO;
        }
        [models addObject:model];
    }
    _publishedModels = [models copy]; return YES;
}
- (BOOL)verifyCommittedStateWithError:(NSError **)error { return [self regenerateHostScriptFilesWithError:error]; }
- (void)reloadHostCache {
    Class cls = NSClassFromString(@"Tampermonkey"); SEL shared = NSSelectorFromString(@"shareInstance"), clear = NSSelectorFromString(@"removeAllUserScriptsFromCache"), save = NSSelectorFromString(@"saveUserScriptToCache:");
    id manager = [cls respondsToSelector:shared] ? ((id (*)(id, SEL))objc_msgSend)(cls, shared) : nil;
    if (!_publishedModels || ![manager respondsToSelector:save]) return;
    if ([manager respondsToSelector:clear]) ((void (*)(id, SEL))objc_msgSend)(manager, clear);
    for (id model in _publishedModels) ((void (*)(id, SEL, id))objc_msgSend)(manager, save, model);
    _publishedModels = nil;
}
- (NSData *)recoverySnapshotWithError:(NSError **)error {
    NSData *sql = FDMRecoverySQLSnapshot(_database, @"t_userscript", FDMBackupScriptColumns(), error); if (!sql) return nil;
    NSString *directory = [self scriptDirectoryWithError:error]; if (!directory) return nil;
    NSMutableDictionary *files = [NSMutableDictionary dictionary];
    NSArray *names = [[NSFileManager defaultManager] contentsOfDirectoryAtPath:directory error:error]; if (!names) return nil;
    NSUInteger total = 0;
    for (NSString *name in names) {
        if (![name.pathExtension isEqual:@"js"]) continue;
        NSString *identifier = name.stringByDeletingPathExtension;
        if (![self fileNameForID:identifier] || ![[self fileNameForID:identifier] isEqual:name]) continue;
        NSData *bytes = FDMReadBoundedFile([NSURL fileURLWithPath:[directory stringByAppendingPathComponent:name]], FDMBackupMaxScriptBytes, error);
        if (!bytes) return nil;
        total += bytes.length; if (total > 16*1024*1024) { if (error) *error = FDMRepoError(@"本地脚本前像超出恢复预算"); return nil; }
        files[name] = [bytes base64EncodedStringWithOptions:0];
    }
    return FDMJSONCanonicalData(@{@"recoverySchema": @2, @"sql": [sql base64EncodedStringWithOptions:0], @"files": files}, error);
}
- (BOOL)restoreRecoverySnapshot:(NSData *)snapshot error:(NSError **)error {
    NSDictionary *root = FDMJSONObjectValue(FDMJSONParseDataBounded(snapshot, 32, 32*1024*1024, error));
    if (![root[@"recoverySchema"] isEqual:@2] || ![root[@"sql"] isKindOfClass:NSString.class] || !FDMJSONObjectValue(root[@"files"])) return NO;
    NSData *sql = [[NSData alloc] initWithBase64EncodedString:root[@"sql"] options:0]; if (!sql) return NO;
    NSString *directory = [self scriptDirectoryWithError:error]; if (!directory) return NO;
    NSArray *live = [self readRowsWithError:error]; if (!live) return NO;
    NSMutableSet *newNames = [NSMutableSet set];
    for (NSDictionary *row in live) { NSString *name = [self fileNameForID:row[@"uuid"]]; if (name) [newNames addObject:name]; }
    for (NSString *name in root[@"files"]) {
        if (![[self fileNameForID:name.stringByDeletingPathExtension] isEqual:name] || ![root[@"files"][name] isKindOfClass:NSString.class]) return NO;
        NSData *bytes = [[NSData alloc] initWithBase64EncodedString:root[@"files"][name] options:0]; if (!bytes || bytes.length > FDMBackupMaxScriptBytes) return NO;
        NSString *path = [directory stringByAppendingPathComponent:name];
        if (![bytes writeToFile:path options:NSDataWritingAtomic error:error]) return NO;
        if (![FDMReadBoundedFile([NSURL fileURLWithPath:path], FDMBackupMaxScriptBytes, error) isEqual:bytes]) return NO;
        [newNames removeObject:name];
    }
    // Only current restored-row names introduced since this before-image can be removed.
    for (NSString *name in newNames) {
        NSString *path = [directory stringByAppendingPathComponent:name];
        if ([[NSFileManager defaultManager] fileExistsAtPath:path] && ![[NSFileManager defaultManager] removeItemAtPath:path error:error]) return NO;
    }
    if (!FDMRecoverySQLRestore(_database, sql, @"t_userscript", FDMBackupScriptColumns(), error)) return NO;
    _publishedModels = nil; return YES;
}

